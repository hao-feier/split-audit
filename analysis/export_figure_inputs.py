"""Export the figure inputs that cannot be read straight from a results JSON.

WHY THIS EXISTS
---------------
``analysis/make_figures.py`` deliberately depends on nothing but small JSON
files under ``results/`` so that figures can be restyled without access to the
18 GB ``data/`` tree (or to torch).  Six of the seven panels already read a
results JSON.  Fig 1 (study regions + spatial split zones) is the exception:
it plots the *geometry* of the split, which lives in the per-region
``metadata.json`` (patch grid + patch coordinates) and the per-region split
index lists under ``data/splits/``.

So this script is the one-time bridge: it collapses that geometry into a
single flat JSON, ``results/fig1_zones.json`` (~100 KB), which is then the
only input Fig 1 needs.

The change-autocorrelation panel (Fig 2) has no such problem --
``analysis/autocorr_decay.py`` already writes
``results/autocorr/change_autocorr.json``, and Fig 2 reads that.

WHAT IS WRITTEN
---------------
    results/fig1_zones.json

        {
          "unit": "km",
          "resolution_m": 10.0,
          "zone_priority": ["train", "val", "test", "buffer"],
          "regions": {
            "<region>": {
              "x_km": [...], "y_km": [...],      # patch centroid, km
              "width_km": ..., "height_km": ..., # full grid extent
              "zones": ["train", null, ...]      # null = not in any zone
            }, ...
          }
        }

    ``zones`` is ``null`` for the two independent test regions (a single test
    block); the panel then draws every patch in the test colour.

Run:  python analysis/export_figure_inputs.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mangrove.paths import RESULTS_ROOT, PROCESSED_ROOT, SPLITS_ROOT
from mangrove.config import PATCH_SIZE

RES_M = 10.0                     # Sentinel-2 grid, metres per pixel
ZONE_PRIORITY = ["train", "val", "test", "buffer"]
OUT_PATH = RESULTS_ROOT / "fig1_zones.json"


def region_geometry(region):
    """Patch-centroid coordinates (km) + grid extent for one region."""
    meta = json.loads((PROCESSED_ROOT / region / "metadata.json").read_text())
    size = meta.get("patch_size", PATCH_SIZE)
    H, W = meta["grid"]
    patches = np.asarray(meta["patches"])
    rows, cols = patches[:, 0], patches[:, 1]
    x = (cols + size / 2.0) * RES_M / 1000.0
    y = (rows + size / 2.0) * RES_M / 1000.0
    return {
        "x_km": [round(float(v), 6) for v in x],
        "y_km": [round(float(v), 6) for v in y],
        "width_km": round(W * RES_M / 1000.0, 6),
        "height_km": round(H * RES_M / 1000.0, 6),
        "n_patches": int(len(patches)),
    }


def region_zones(region, n_patches):
    """Per-patch split zone; None where the patch belongs to no zone.

    Zones are resolved in ZONE_PRIORITY order so the output is deterministic
    even if the split files were ever to overlap.
    """
    members = {}
    for zone in ZONE_PRIORITY:
        p = SPLITS_ROOT / f"{region}_{zone}.json"
        if p.exists():
            for i in json.loads(p.read_text()):
                members.setdefault(int(i), zone)
    return [members.get(i) for i in range(n_patches)], len(members)


def main():
    out = {
        "_comment": ("Generated by analysis/export_figure_inputs.py -- do not "
                     "edit by hand. Consumed by analysis/make_figures.py fig1."),
        "unit": "km",
        "resolution_m": RES_M,
        "zone_priority": ZONE_PRIORITY,
        "regions": {},
    }
    for region in ("vietnam", "beilunhe", "zhanjiang"):
        geom = region_geometry(region)
        zones, n_zoned = region_zones(region, geom["n_patches"])
        present = sorted({z for z in zones if z})
        geom["zones"] = zones
        # A region is "zoned" when the panel has more than one zone to
        # colour by.  The two independent test regions are a single test
        # block, so there is no partition to draw and the panel draws them
        # as one uniform block instead.
        geom["zoned"] = len(present) > 1
        out["regions"][region] = geom
        print(f"  {region}: {geom['n_patches']} patches, {n_zoned} assigned, "
              f"zones={present or ['-']}, zoned={geom['zoned']}, "
              f"extent {geom['width_km']:.2f} x {geom['height_km']:.2f} km")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(json.dumps(out, indent=1))
    print(f"\nwrote {OUT_PATH}  ({OUT_PATH.stat().st_size / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
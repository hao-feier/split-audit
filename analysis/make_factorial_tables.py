"""GENERATE tab:factorial and tab:rand-sweep.

Both tables were hand-entered in paper/main.tex and had drifted 0.1-1.0 pp from
the JSON they claim to summarise, which is the mechanical cause of the abstract's
protocol-attribution garble. This script regenerates both blocks from

    results/uniform/ir_factorial.json          (tab:factorial)
    results/uniform/random_split/comparison.json (tab:rand-sweep)

and rewrites them in place in paper/main.tex between the AUTO-GENERATED markers.
Every number in both tables therefore traces to a result file.

It also prints the drift against whatever is currently hand-entered, so the size
of the correction is visible rather than silent.

Run:
    python analysis/make_factorial_tables.py            # write + report drift
    python analysis/make_factorial_tables.py --check     # report only, no write
"""
import argparse
import json
import re
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAPER = ROOT / "paper" / "main.tex"

MODELS = [
    ("unet", "U-Net"),
    ("unet_cbam", "U-Net+CBAM"),
    ("unet_cbam_msa", "U-Net+CBAM+MSA"),
    ("deeplabv3plus", "DeepLabv3+"),
    ("temporal_unet", "Temporal U-Net"),
]

BEGIN = "%% ===== AUTO-GENERATED by analysis/make_factorial_tables.py"
END = "%% ===== END AUTO-GENERATED (factorial tables) ====="


def load():
    ir = json.loads((ROOT / "results" / "uniform" / "ir_factorial.json").read_text())
    cmp_ = json.loads(
        (ROOT / "results" / "uniform" / "random_split" / "comparison.json").read_text())
    return ir, cmp_


def _excluded(cmp_):
    """Collapsed run keys to drop (all three cells use the same criterion)."""
    out = set()
    for key in cmp_.get("_config", {}).get("excluded_collapsed_runs", []):
        out.add(key)
    return out


def factorial_rows(ir):
    """tab:factorial body rows from the excl_collapse block (the primary
    variant: the six collapsed runs are excluded, as the caption states)."""
    rows = []
    for key, label in MODELS:
        m = ir["per_model"].get(key)
        if m is None:
            continue
        blk = m.get("excl_collapse", m)
        rows.append({
            "label": label,
            "II": blk["II"], "RI": blk["RI"], "RR": blk["RR"], "IR": blk["IR"],
            "dTrain": blk["dTrain_pp"], "dTest": blk["dTest_pp"],
            "dInt": blk["dInt_pp"], "IR_std": blk.get("IR_std"),
            "n_runs": blk.get("n_runs", m.get("n_runs")),
        })
    return rows


def sweep_rows(cmp_, ir):
    """tab:rand-sweep body rows.

    Inflation is measured against the I/I cell of the PRIMARY five-seed sweep
    (ir_factorial.json -> excl_collapse.II), not against the counterfactual
    sweep's own 3-run isolated cell (rnd_iso). The headline quantity asks how
    much the interleaved protocol inflates relative to the honest protocol that
    the rest of the paper reports, so the honest arm must be the primary one.
    rnd_iso is a 3-run re-estimate of the same honest quantity and sits higher
    for 4 of 5 models, which would shrink the measured inflation by 0.4-5.2 pp.

    Run-to-run spread is over the counterfactual runs with that fixed honest
    reference: infl_run = 100 * (rnd_rnd[run] - II).
    """
    drop = _excluded(cmp_)
    rows = []
    for key, label in MODELS:
        c = cmp_.get(key)
        m = ir["per_model"].get(key)
        if c is None or m is None:
            continue
        blk = m.get("excl_collapse", m)
        II = blk["II"]
        dtrain = blk.get("dTrain_pp")
        per_run = []
        for run, a in c["rnd_rnd"].items():
            if run in drop:
                continue
            per_run.append((run.split("-")[0], 100.0 * (a["F1_change"] - II)))
        if not per_run:
            continue
        vals = [v for _, v in per_run]
        by_split = {}
        for k, v in per_run:
            by_split.setdefault(k, []).append(v)
        split_means = [st.mean(v) for v in by_split.values()]
        rows.append({
            "label": label,
            "mean": st.mean(vals),
            "std": st.stdev(vals) if len(vals) > 1 else 0.0,
            "lo": min(split_means), "hi": max(split_means),
            "dTrain": dtrain, "II": II, "n": len(vals),
            "n_splits": len(by_split),
        })
    return rows


def fmt_ppm(v):
    return "%+.1f" % v


def render_factorial(rows):
    out = []
    out.append(r"\begin{tabular}{l cccc ccc}")
    out.append(r"\toprule")
    out.append(r" & \multicolumn{4}{c}{Cells (change $F1$)} "
               r"& \multicolumn{3}{c}{Components (pp)} \\")
    out.append(r"Model & I/I & R/I & R/R & I/R & $\Delta_{\mathrm{train}}$ "
               r"& $\Delta_{\mathrm{test}}$ & $\Delta_{\mathrm{int}}$ \\")
    out.append(r"\midrule")
    for r in rows:
        out.append("%s & %.3f & %.3f & %.3f & %.3f & $%s$ & $%s$ & $%s$ \\\\" % (
            r["label"], r["II"], r["RI"], r["RR"], r["IR"],
            fmt_ppm(r["dTrain"]), fmt_ppm(r["dTest"]), fmt_ppm(r["dInt"])))
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    lo = min(r["dTest"] + r["dInt"] for r in rows)
    hi = max(r["dTest"] + r["dInt"] for r in rows)
    return "\n".join(out), lo, hi


def render_sweep(rows):
    out = []
    out.append(r"\begin{tabular}{lrrr}")
    out.append(r"\toprule")
    out.append(r"Model & Inflation (mean $\pm$ std) & Per-split range "
               r"& Training effect \\")
    out.append(r"\midrule")
    for r in rows:
        out.append("%s & $%+.1f \\pm %.1f$ & $%.1f$--$%.1f$ & $%s$ \\\\" % (
            r["label"], r["mean"], r["std"], r["lo"], r["hi"], fmt_ppm(r["dTrain"])))
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="report drift only, do not write main.tex")
    args = ap.parse_args()

    ir, cmp_ = load()
    frows = factorial_rows(ir)
    srows = sweep_rows(cmp_, ir)
    ftab, lo, hi = render_factorial(frows)
    stab = render_sweep(srows)

    print("== tab:factorial (excl_collapse) ==")
    for r in frows:
        print("   %-16s II=%.3f RI=%.3f RR=%.3f IR=%.3f  dTrain=%+.1f "
              "dTest=%+.1f dInt=%+.1f  (composite %+.1f)"
              % (r["label"], r["II"], r["RI"], r["RR"], r["IR"],
                 r["dTrain"], r["dTest"], r["dInt"], r["dTest"] + r["dInt"]))
    print("   composite test-side (RR-RI) spans %+.1f .. %+.1f pp" % (lo, hi))
    print()
    print("== tab:rand-sweep ==")
    for r in srows:
        print("   %-16s %+.1f +- %.1f  per-split %.1f..%.1f  dTrain=%+.1f  "
              "(n=%d runs, %d splits)"
              % (r["label"], r["mean"], r["std"], r["lo"], r["hi"],
                 r["dTrain"], r["n"], r["n_splits"]))
    print()

    # ---- compare against what is currently in the file ----
    txt = PAPER.read_text()
    cur_f = re.findall(
        r"^(U-Net(?:\+CBAM(?:\+MSA)?|)|DeepLabv3\+|Temporal U-Net) & "
        r"([\d.]+) & ([\d.]+) & ([\d.]+) & ([\d.]+) & \$([+\-][\d.]+)\$ & "
        r"\$([+\-][\d.]+)\$ & \$([+\-][\d.]+)\$", txt, re.M)
    if cur_f:
        print("drift vs currently hand-entered tab:factorial:")
        cmap = {r[0]: r[1:] for r in cur_f}
        for r in frows:
            c = cmap.get(r["label"])
            if not c:
                continue
            new = ("%.3f" % r["II"], "%.3f" % r["RI"], "%.3f" % r["RR"],
                   "%.3f" % r["IR"], fmt_ppm(r["dTrain"]), fmt_ppm(r["dTest"]),
                   fmt_ppm(r["dInt"]))
            diffs = [(i, c[i], new[i]) for i in range(7) if c[i] != new[i]]
            if diffs:
                print("   %-16s %s" % (r["label"],
                                       "; ".join("col%d %s->%s" % d for d in diffs)))
            else:
                print("   %-16s unchanged" % r["label"])
        print()

    if args.check:
        print("--check: no write performed.")
        return

    # ---- rewrite tab:factorial body ----
    pat_f = re.compile(
        r"(\\begin\{tabular\}\{l cccc ccc\}.*?\\end\{tabular\})", re.S)
    if pat_f.search(txt):
        txt = pat_f.sub(lambda m: BEGIN + " tab:factorial\n" + ftab + "\n" + END,
                        txt, count=1)
    else:
        print("!! tab:factorial tabular not found -- left untouched")

    # ---- rewrite tab:rand-sweep body ----
    pat_s = re.compile(
        r"(\\begin\{tabular\}\{lrrr\}.*?\\end\{tabular\})", re.S)
    if pat_s.search(txt):
        txt = pat_s.sub(lambda m: BEGIN + " tab:rand-sweep\n" + stab + "\n" + END,
                        txt, count=1)
    else:
        print("!! tab:rand-sweep tabular not found -- left untouched")

    PAPER.write_text(txt)
    print("rewrote tab:factorial and tab:rand-sweep in paper/main.tex")


if __name__ == "__main__":
    sys.exit(main())

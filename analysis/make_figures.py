# Fig 1 -- study regions + spatial split zones
# ======================================================================
def fig1_spatial_split():
    """Patch layout and zone assignment in the three study regions.

    Three defects in the previous version are fixed here.

    1. It drew a grey ``axvspan`` at the 55th--65th x percentile *and* coloured
       the real buffer patches grey, so the buffer appeared twice and the band
       was a crude stand-in for a zone that is already in the data.  The
       approximation is gone; the buffer is drawn once, from the data, and now
       appears in the legend like every other zone.
    2. The three panels shared one physical height but each was drawn over its
       own extent (51x78, 63x65, 83x55 km), so the regions were rendered at
       different zooms and their apparent sizes were not comparable.  All three
       panels now span one common km window, which puts them on a single scale,
       makes them the same size, and lets one scale bar serve the whole figure.
    3. Per-panel legends sat on top of the patch cloud they labelled.  There is
       now a single shared key below the panels.
    """
    if not ZONES_JSON.exists():
        print("fig1 skipped (no results/fig1_zones.json); "
              "run analysis/export_figure_inputs.py first")
        return
    Z = json.loads(ZONES_JSON.read_text())["regions"]
    SCALE_KM = 10.0
    # Common window across regions: one scale for the whole figure.
    WMAX = max(R["width_km"] for R in Z.values())
    HMAX = max(R["height_km"] for R in Z.values())

    def draw(ax, key, title, letter, with_scalebar):
        R = Z[key]
        x = np.asarray(R["x_km"])
        y = np.asarray(R["y_km"])
        Rw, Rh = R["width_km"], R["height_km"]
        ax.add_patch(Rectangle((0, 0), Rw, Rh, fill=False,
                               edgecolor="#BBBBBB", lw=0.8, ls=(0, (4, 3))))
        if R["zoned"]:
            cols = [fs.ZONE_COLOR[z or "test"] for z in R["zones"]]
        else:
            cols = [fs.ZONE_COLOR["test"]] * len(x)
        ax.scatter(x, y, s=26, color=cols, edgecolor="white", lw=0.35, zorder=3)
        ax.set_xlim(-WMAX * 0.02, WMAX * 1.02)
        ax.set_ylim(-HMAX * 0.02, HMAX * 1.02)
        ax.set_aspect("equal")
        ax.set_xticks([]); ax.set_yticks([])
        fs.panel_title(ax, letter, title, fs=FS_PANEL)
        # extent, top-right inside the axes so it cannot meet the scale bar
        ax.text(WMAX * 0.985, HMAX * 0.975, f"{Rw:.0f}$\\times${Rh:.0f} km",
                ha="right", va="top", fontsize=FS_NOTE, color=fs.GREY)
        if with_scalebar:
            # inside the axes: drawn below the lower spine it collided with the
            # frame and with the shared legend
            y0 = HMAX * 0.055
            x0 = WMAX * 0.10
            ax.plot([x0, x0 + SCALE_KM], [y0, y0], color="#333333", lw=2.2,
                    solid_capstyle="butt", zorder=6)
            ax.text(x0 + SCALE_KM / 2, y0 + HMAX * 0.015, f"{SCALE_KM:g} km",
                    ha="center", va="bottom", fontsize=FS_NOTE, color="#333333")
        fs.strip_top_right(ax)

    fig, (a1, a2, a3) = plt.subplots(1, 3, figsize=(PRINT_W, PRINT_W / 2.75))
    draw(a1, "vietnam", "Red River Delta, Vietnam\n(training region)", "a", True)
    draw(a2, "beilunhe", "Beilunhe estuary, China\n(independent test)", "b", False)
    draw(a3, "zhanjiang", "Zhanjiang, China\n(independent test)", "c", False)

    # One shared key below the panels; a per-panel legend sat on top of the
    # patch cloud it was labelling.
    ZONE_LBL = {"train": "training", "val": "validation",
                "buffer": "2 km buffer", "test": "test"}
    handles = [a1.scatter([], [], s=26, color=fs.ZONE_COLOR[z],
                          edgecolor="white", lw=0.3, label=ZONE_LBL[z])
               for z in ("train", "val", "buffer", "test")]
    fig.legend(handles=handles, fontsize=FS_LEGEND, ncol=4, frameon=False,
               loc="lower center", bbox_to_anchor=(0.5, -0.015),
               columnspacing=2.2, handletextpad=0.5)

    fig.tight_layout(w_pad=1.4, rect=[0, 0.075, 1, 0.965])
    fs.save(fig, "fig1_spatial_split")
    print("fig1 saved")



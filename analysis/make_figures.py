# Fig 2 -- change-label spatial autocorrelation decay
# ======================================================================
def fig2_autocorr_decay():
    """Change-label co-occurrence enrichment vs pixel separation.

    Reads the curve computed by analysis/autocorr_decay.py, which measures it
    on the raw change labels (model-free).  Enrichment is 1 at independence.
    """
    if not AUTOCORR_JSON.exists():
        print("fig2 skipped (no results/autocorr/change_autocorr.json); "
              "run analysis/autocorr_decay.py first")
        return
    J = json.loads(AUTOCORR_JSON.read_text())
    REG2 = [r for r in ("vietnam", "beilunhe", "zhanjiang") if r in J]
    # Axis ladder, NOT the measured lags: it sets the displayed range and the
    # tick labels (10 m ... 8 km) independently of how many lags the data has.
    # 8000 m = 800 px exceeds the 512-px patch, so the measured curve stops at
    # 4000 m; the axis deliberately runs past it.
    LAGS_M = [10, 25, 50, 100, 250, 500, 1000, 2000, 4000, 8000]
    RLABEL = {"vietnam": "Vietnam (train)", "beilunhe": "Beilunhe (test)",
              "zhanjiang": "Zhanjiang (test)"}
    RCOLOR = {"vietnam": "#0072B2", "beilunhe": "#E69F00",
              "zhanjiang": "#009E73"}

    for region in REG2:
        print(f"  [{region}] change_frac={J[region]['change_fraction']:.4f}")

    fig, ax = plt.subplots(figsize=(PRINT_W, PRINT_W / 1.62))
    for region in REG2:
        c = J[region]["curve"]
        ax.plot([p["lag_m"] for p in c], [p["enrichment"] for p in c],
                marker="o", lw=1.6, color=RCOLOR[region], label=RLABEL[region])
    ax.axhline(1.0, color="#888888", lw=0.9, ls="--")
    ax.text(LAGS_M[-1], 1.02, "independence", ha="right", va="bottom",
            fontsize=FS_NOTE, color="#666666")
    ax.axhline(2.0, color="#CCCCCC", lw=0.8, ls=":")
    ax.text(LAGS_M[0], 2.02, "2x", ha="left", va="bottom", fontsize=FS_NOTE, color="#999999")
    ax.set_xscale("log")
    ax.set_xticks([10, 100, 1000, 8000])
    ax.set_xticklabels(["10 m", "100 m", "1 km", "8 km"])
    ax.set_xlabel("separation between two pixels")
    ax.set_ylabel("change co-occurrence\nenrichment over independence")
    ax.set_xlim(LAGS_M[0] * 0.8, LAGS_M[-1] * 1.25)
    ymax = max(J[r]["curve"][0]["enrichment"] for r in REG2)
    ax.set_yscale("log")
    ax.set_ylim(0.1, ymax * 1.4)
    ax.legend(loc="upper right", fontsize=FS_LEGEND)
    # No in-figure title: the panel name lives in the LaTeX caption.
    # This figure was the only one without an explicit layout pass, so the
    # default subplot margins clipped the axis labels once the canvas width
    # was corrected to the real \textwidth.
    fig.tight_layout()
    fs.save(fig, "fig2_autocorr_decay")
    print("fig2 saved")



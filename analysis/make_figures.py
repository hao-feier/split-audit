FS_NOTE = 6.8         # auxiliary annotations (n=, scale bar, extent, ...)
FS_TICK_ROT = 6.5     # rotated long tick labels (fig5b)


def mean_std(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return 0.0, 0.0
    return float(np.mean(vals)), (float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0)



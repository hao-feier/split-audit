def fig5_roc_pr():
    p = RESULTS_ROOT / "roc_pr_curves.json"
    if not p.exists():
        print("fig7 skipped (no results/roc_pr_curves.json)"); return
    J = json.loads(p.read_text())
    curves = J.get("splits", {})
    if not curves or "fpr" not in curves.get("honest", {}):
        print("fig7 skipped (roc_pr_curves.json has no curves;"
              " re-run analysis/make_roc_pr_curves.py)"); return

    # honest solid blue; leaky k1 solid / k2 dashed / k3 dotted orange
    styles = [("honest", HONEST_C, "-"), ("leaky_k1", LEAKY_C, "-"),
              ("leaky_k2", LEAKY_C, "--"), ("leaky_k3", LEAKY_C, ":")]

    def curve_label(name):
        if name == "honest":
            return "honest (buffered)"
        if name == "leaky_k1":
            return "leaky $k$1\u2013$k$3"
        return None

    fig, axes = plt.subplots(1, 2, figsize=(PRINT_W, PRINT_W / 2.45))

    ax = axes[0]
    for name, color, ls in styles:
        if name not in curves:
            continue
        c = curves[name]
        ax.plot(c["fpr"], c["tpr"], color=color, linestyle=ls, lw=1.5,
                label=curve_label(name))
    ax.plot([0, 1], [0, 1], "k--", lw=0.5, alpha=0.3)
    ax.axvline(0.01, color="grey", lw=0.5, ls=":", alpha=0.5)
    ax.text(0.018, 0.11, "FPR=0.01", fontsize=FS_NOTE, color="grey")
    ax.set_xlabel("False Positive Rate")
    ax.set_ylabel("True Positive Rate")
    fs.panel_title(ax, "a", "", fs=FS_PANEL)
    ax.set_xlim(-0.02, 1.05)
    ax.set_ylim(-0.02, 1.05)
    ax.grid(alpha=0.15)

    ax = axes[1]
    for name, color, ls in styles:
        if name not in curves:
            continue
        c = curves[name]
        ax.plot(c["recall"], c["precision"], color=color, linestyle=ls, lw=1.5,
                label=curve_label(name))
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    fs.panel_title(ax, "b", "", fs=FS_PANEL)
    ax.set_xlim(-0.02, 1.05)
    ax.set_ylim(0, 1.05)
    ax.grid(alpha=0.15)

    # One figure-level legend: both panels carry the same two series, so a
    # per-panel key duplicated the same information twice and, placed inside
    # the axes, sat on top of the curves.
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, fontsize=FS_LEGEND, ncol=2, frameon=False,
               loc="upper center", bbox_to_anchor=(0.5, 0.998),
               columnspacing=2.0, handletextpad=0.6)

    fig.tight_layout(rect=[0.082, 0.0, 0.988, 0.90])
    fs.symmetrize_margins(fig, list(axes))
    # No in-figure footnote: the model/seed, the split draws and the
    # prevalence caveat all belong in the LaTeX caption.
    fs.save(fig, "fig5_roc_pr")
    print("fig7 saved")



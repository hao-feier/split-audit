"""Generate all seven paper figures (vector PDF + 300-DPI PNG).

SELF-CONTAINED BY DESIGN.  This script reads ONLY small JSON files under
results/ -- never data/, never torch, never the mangrove package -- so the
whole figure set can be restyled from a checkout of this file +
analysis/figstyle.py + the JSONs listed below (~0.5 MB in total).  This is
what makes the figures reviewable in isolation.  The two inputs that are not
already results of an analysis stage are regenerated by:

  python analysis/export_figure_inputs.py   -> results/fig1_zones.json
  python analysis/autocorr_decay.py         -> results/autocorr/change_autocorr.json

JSON INPUTS
    results/fig1_zones.json                  fig 1
    results/autocorr/change_autocorr.json    fig 2
    results/uniform/random_split/comparison.json                        fig 3
    results/collapse_reconciliation.json,
    results/prevalence_roc.json,
    results/uniform/random_split_k1/metrics_changeformer_s2026.json    fig 4
    results/decomposition_6order.json                                   fig 5
    results/metrics_summary.json                                      fig 6
    results/roc_pr_curves.json  (by analysis/make_roc_pr_curves.py)    fig 7

SIZING INVARIANT: main.tex includes every figure at `width=\textwidth`
(= 5.4567 in for this MDPI layout, measured from the class -- see
analysis/figstyle.py PRINT_W_IN).  If a figure's canvas is PRINT_W inches
wide, LaTeX scales it by 1.0, so the point sizes written below are the point
sizes on the page.  Keep figsize width at PRINT_W when changing font sizes, or
the type will not match the numbers in this file.  analysis/figure_qa.py
re-measures the real \textwidth and fails if the canvas drifts from it.

Fig 1  fig1_spatial_split.pdf    study regions + spatial split zones
Fig 2  fig2_autocorr_decay.pdf   change-label spatial autocorrelation decay
Fig 3  fig3_per_arch_gap.pdf     per-arch F1: honest vs leaky (uniform)
Fig 4  fig4_collapse.pdf         collapsed-run confusion matrix
Fig 5  fig5_roc_pr.pdf           ROC / PR curves, honest vs leaky arms
Fig 6  fig6_decomposition.pdf    F1 gap decomposition (TPR/FPR/prev)
Fig 7  fig7_cross_region.pdf     per-arch F1 at three evaluation sites

All styling from analysis/figstyle.py.  No model inference or GPU required.
Run:  python analysis/make_figures.py
"""

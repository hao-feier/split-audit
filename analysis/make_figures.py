# Font-size ladder (single source of truth *inside this file*): the same text
# role uses the same point size across all seven figures.  Panel/axis/tick
# sizes match figstyle.RC; the legend/annotation sizes are pinned here because
# figstyle leaves them as per-figure magic numbers.  Two sizes are kept
# deliberately smaller than the ladder for layout reasons, and are named so
# they read as intentional rather than as drift:

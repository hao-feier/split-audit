# Fig 3 -- per-architecture F1: honest vs leaky (uniform weighting)
# ======================================================================
def fig3_per_arch_gap():
    """Dumbbell (connected-dot) plot: honest vs leaky F1 per architecture.

    A grouped bar chart of 10 architectures x 2 protocols was the previous
    design.  It had two defects: the 10 rotated architecture labels collided,
    and the quantity the paper actually argues about -- the *gap* between the
    arms -- had to be read as the difference of two bar heights.  A dumbbell
    makes the gap the primary visual object: one row per architecture, the two
    arms as two markers joined by a connector, the inflation annotated on the
    connector.

    Rows are sorted by inflation so that the architecture-invariance of the
    effect is legible as the shape of the ordering; the focal architecture
    keeps its bold label so it stays findable.
    """
    p = RESULTS_ROOT / "uniform" / "random_split" / "comparison.json"
    if not p.exists():
        print("fig3 skipped (no uniform/random_split/comparison.json)"); return
    comp = json.loads(p.read_text())
    models = [m for m in DL_MODELS if m in comp]

    rows = []
    for m in models:
        hv = [v["F1_change"] for v in comp[m].get("rnd_iso", {}).values()
              if v["F1_change"] is not None]
        lv = [v["F1_change"] for v in comp[m].get("rnd_rnd", {}).values()
              if v["F1_change"] is not None]
        if not hv or not lv:
            continue
        h_mu, h_sd = mean_std(hv)
        l_mu, l_sd = mean_std(lv)
        # n is the number of split draws per arm; the two arms are always
        # run-paired, so report the (equal) per-arm count.
        assert len(hv) == len(lv), f"{m}: arms unbalanced ({len(hv)} vs {len(lv)})"
        rows.append({"model": m, "h": h_mu, "h_sd": h_sd, "l": l_mu, "l_sd": l_sd,
                     "gap_pp": (l_mu - h_mu) * 100, "n": len(hv)})

    # Top = largest inflation; invert so the best y-coordinate is the top row.
    rows.sort(key=lambda r: r["gap_pp"])
    ys = np.arange(len(rows))[::-1].astype(float)

    fig, ax = plt.subplots(figsize=(PRINT_W, PRINT_W / 1.62))

    for y, r in zip(ys, rows):
        h, l = r["h"], r["l"]
        # connector: the gap, drawn as the primary object
        ax.plot([h, l], [y, y], color="#C8C8C8", lw=1.6, zorder=1,
                solid_capstyle="round")
        ax.errorbar(h, y, xerr=r["h_sd"], fmt="o", ms=5.0, color=HONEST_C,
                    ecolor=HONEST_C, elinewidth=1.0, capsize=0, zorder=3,
                    markeredgecolor="white", markeredgewidth=0.5)
        ax.errorbar(l, y, xerr=r["l_sd"], fmt="o", ms=5.0, color=LEAKY_C,
                    ecolor=LEAKY_C, elinewidth=1.0, capsize=0, zorder=3,
                    markeredgecolor="white", markeredgewidth=0.5)
        # inflation label on the connector midpoint, lifted clear of the line
        ax.text(0.5 * (h + l), y + 0.17, f"+{r['gap_pp']:.0f}",
                ha="center", va="bottom", fontsize=FS_DATA, color="#333333",
                fontweight="bold")

    lbls = []
    for r in rows:
        t = LABEL[r["model"]]
        lbls.append(t)
    ax.set_yticks(ys)
    ax.set_yticklabels(lbls, fontsize=FS_TICK)
    for tick, r in zip(ax.get_yticklabels(), rows):
        if r["model"] == fs.PROPOSED:
            tick.set_fontweight("bold")

    # n column, right-aligned past the plot area.  ChangeFormer-style ran only
    # 4 split draws rather than 8; showing that is part of reporting honestly.
    XMAX = 0.72
    ax.set_xlim(0, XMAX)
    ax.set_ylim(-0.75, len(rows) - 0.25)
    for y, r in zip(ys, rows):
        ax.annotate(f"n={r['n']}", xy=(1.0, y), xycoords=("axes fraction", "data"),
                    xytext=(4, 0), textcoords="offset points",
                    ha="left", va="center", fontsize=FS_NOTE, color=fs.GREY,
                    annotation_clip=False)

    ax.set_xticks([0.0, 0.2, 0.4, 0.6])
    ax.xaxis.grid(True, alpha=0.18, zorder=0)
    ax.set_axisbelow(True)
    fs.strip_top_right(ax)
    ax.tick_params(axis="y", length=0)
    ax.set_xlabel("Change-class $F1$ (mean over split draws)")

    # legend above the axes, never over the data
    h_ln, = ax.plot([], [], "o", ms=5.0, color=HONEST_C, markeredgecolor="white",
                    markeredgewidth=0.5, label="Honest (buffer-separated)")
    l_ln, = ax.plot([], [], "o", ms=5.0, color=LEAKY_C, markeredgecolor="white",
                    markeredgewidth=0.5, label="Leaky (interleaved)")
    ax.legend(handles=[h_ln, l_ln], fontsize=FS_LEGEND, ncol=2, frameon=False,
              loc="lower left", bbox_to_anchor=(0.0, 1.01),
              columnspacing=1.6, handletextpad=0.5)

    fig.tight_layout(rect=[0, 0.0, 0.94, 1])
    fs.save(fig, "fig3_per_arch_gap")
    print("fig3 saved")



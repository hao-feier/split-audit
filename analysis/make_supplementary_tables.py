# Primary comparison = uniform (unweighted) sweep; sqrt sweep supplies the
# pixel baselines (no class weights). The leave-one-cluster-out analysis is
# taken from LOCO_ROOT (defaults to results/uniform).
PRIMARY_ROOT = Path(os.environ.get("MANGROVE_PRIMARY_ROOT",
                                   str(ROOT / "results" / "uniform")))
LOCO_ROOT = Path(os.environ.get("MANGROVE_LOCO_ROOT", str(ROOT / "results" / "uniform"))
                                   )

BEGIN = "% ===== AUTO-GENERATED by analysis/make_supplementary_tables.py \u2014 do not edit ====="
END = "% ===== END AUTO-GENERATED by analysis/make_supplementary_tables.py ====="

ALL_MODELS = ["random_forest", "svm_rbf", "unet", "unet_cbam", "unet_msa",
              "unet_cbam_msa", "deeplabv3plus", "deeplabv3plus_pre",
              "temporal_unet", "temporal_unet_gn", "fc_siam", "changeformer"]
DEEP = [m for m in ALL_MODELS if m not in ("random_forest", "svm_rbf")]
DEEP_NOCF = [m for m in DEEP if m != "changeformer"]
# tab:main order (9 deep models) for the LOCO table
LOCO_MODELS = ["unet", "unet_cbam", "deeplabv3plus", "temporal_unet",
               "temporal_unet_gn", "fc_siam", "changeformer",
               "deeplabv3plus_pre", "unet_cbam_msa"]
LABEL = {
    "unet": "U-Net (Exp0)",
    "unet_cbam": "U-Net+CBAM (Exp1)",
    "unet_msa": "U-Net+MSA (ablation)",
    "unet_cbam_msa": "U-Net+CBAM+MSA",
    "deeplabv3plus": "DeepLabv3+",
    "deeplabv3plus_pre": "DeepLabv3+ (pretrained)",
    "temporal_unet": "Temporal U-Net",
    "temporal_unet_gn": "Temporal U-Net (GroupNorm)",
    "fc_siam": "FC-Siam",
    "changeformer": "ChangeFormer-style",
    "random_forest": "Random Forest (pixel)",
    "svm_rbf": "SVM (RBF, pixel)",
}
REGIONS = ["within", "beilunhe", "zhanjiang"]
REGION_TITLE = {"within": "Within (Vietnam)", "beilunhe": "Beilunhe",
                "zhanjiang": "Zhanjiang"}
CLASSES = ["stable_mangrove", "loss", "gain", "stable_background"]
CLASS_TITLE = ["Stable mangrove", "Loss", "Gain", "Stable background"]


def ms(vals, nd=3):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    mu = float(np.mean(vals))
    if len(vals) == 1:
        return f"{mu:.{nd}f}"
    sd = float(np.std(vals, ddof=1))
    return f"{mu:.{nd}f}\\,\\scriptsize$\\pm${sd:.{nd}f}"


def per_seed_vals(runs, model, region, key):
    s = runs.get(model, {})
    return [s[seed].get(region, {}).get(key) for seed in s]


def cm_stats(runs, model, region):
    """Per-seed (pred_change_frac, omission, commission) from the 4x4 CM."""
    out = []
    s = runs.get(model, {})
    for seed in s:
        cm = s[seed].get(region, {}).get("cm")
        if not cm:
            out.append(None)
            continue
        cm = np.asarray(cm, dtype=np.float64)
        total = cm.sum()
        tp = cm[np.ix_([1, 2], [1, 2])].sum()
        fn = cm[np.ix_([1, 2], [0, 3])].sum()
        fp = cm[np.ix_([0, 3], [1, 2])].sum()
        out.append((cm[:, [1, 2]].sum() / total,
                    fn / max(tp + fn, 1),
                    fp / max(tp + fp, 1)))
    return out


def main():
    sqrt_runs = json.loads((RESULTS_ROOT / "metrics_summary.json").read_text())
    pf = PRIMARY_ROOT / "metrics_summary.json"
    runs = ({**sqrt_runs, **json.loads(pf.read_text())}
            if PRIMARY_ROOT.resolve() != RESULTS_ROOT.resolve() and pf.exists()
            else sqrt_runs)
    loco = json.loads((LOCO_ROOT / "leave_one_cluster_out.json").read_text())
    out = ["% AUTO-GENERATED by analysis/make_supplementary_tables.py — do not edit.",
           "% Sources: results/metrics_summary.json, results/leave_one_cluster_out.json", ""]

    # ---- predicted change fraction / omission / commission -----------------
    out += ["\\begin{table}[H]",
            "\\caption{Change-rate budget per model and evaluation region"
            ". \\emph{Reference change}: fraction of pixels that "
            "are change in the GMW labels (a property of the region). "
            "\\emph{Predicted change}: fraction of pixels predicted as loss or "
            "gain, i.e.\\ the sum of the change \\emph{prediction} columns of the "
            "$4\\times4$ confusion matrix (true $\\times$ prediction), "
            "mean $\\pm$ std over the five seeds 2026--2030. Omission = missed "
            "true change / true change; commission = false change / predicted "
            "change.}",
            "\\label{tab:predchange}",
            "\\begin{adjustwidth}{-\\extralength}{0cm}",
            "\\small",
            "\\begin{tabularx}{\\fulllength}{l>{\\raggedright\\arraybackslash}X rrrr}",
            "\\toprule",
            "Model & Region & Reference change & Predicted change & Omission & Commission \\\\",
            "\\midrule"]
    ref_change = {}
    for model in ALL_MODELS:
        if model not in runs:
            continue
        first = True
        for region in REGIONS:
            stats = cm_stats(runs, model, region)
            if not any(x is not None for x in stats):
                continue
            if region not in ref_change:
                c = [x[0] for x in stats if x is not None]
                ref_change[region] = float(np.mean([
                    np.asarray(runs[model][seed][region]["cm"], dtype=np.float64)[[1, 2], :].sum()
                    / np.asarray(runs[model][seed][region]["cm"], dtype=np.float64).sum()
                    for seed in runs[model] if runs[model][seed].get(region, {}).get("cm")]))
            vals = [x for x in stats if x is not None]
            pc = [v[0] for v in vals]
            if len(pc) > 1:
                pc_str = ("{:.2f}\\,\\scriptsize$\\pm${:.2f}".format(
                    100 * float(np.mean(pc)), 100 * float(np.std(pc, ddof=1))))
            else:
                pc_str = "{:.2f}".format(100 * float(np.mean(pc)))
            out.append("{} & {} & {:.2f}\\% & {}\\% & {} & {} \\\\".format(
                LABEL[model] if first else "",
                REGION_TITLE[region],
                100 * ref_change[region],
                pc_str,
                ms([v[1] for v in vals]), ms([v[2] for v in vals])))
            first = False
        out.append("\\addlinespace")
    out += ["\\bottomrule", "\\end{tabularx}", "\\end{adjustwidth}",
            "\\end{table}", ""]

    # ---- per-class F1 ranges ------------------------------------------------
    def class_f1_range(models, region=None):
        """per-class (min, max) of the 5-seed-mean F1 over the model set;
        region=None pools regions (same basis as tab:perclass)."""
        regions = [region] if region else REGIONS
        res = []
        for cls in CLASSES:
            vals = []
            for m in models:
                for rg in regions:
                    per_seed = [runs[m][seed].get(rg, {}).get("per_class", {}).get(cls, {}).get("F1")
                                for seed in runs.get(m, {})]
                    per_seed = [v for v in per_seed if v is not None]
                    if per_seed:
                        vals.append(float(np.mean(per_seed)))
            res.append((float(np.min(vals)), float(np.max(vals))))
        return res

    # [region0, region1, region2, pooled] x 4 classes
    r_all = [class_f1_range(ALL_MODELS, rg) for rg in REGIONS] + [class_f1_range(ALL_MODELS)]
    r_deep = [class_f1_range(DEEP, rg) for rg in REGIONS] + [class_f1_range(DEEP)]
    r_nocf = [class_f1_range(DEEP_NOCF, rg) for rg in REGIONS] + [class_f1_range(DEEP_NOCF)]

    def rng(v):
        return f"{v[0]:.2f}--{v[1]:.2f}"

    out += ["\\begin{table}[H]",
            "\\caption{Per-class $F1$ ranges across models. For "
            "each class and region, the min--max of the 5-seed-mean per-class $F1$ "
            "(same basis as Table~\ref{tab:perclass}) over the model sets: all twelve models; the ten "
            "deep models (pixel baselines excluded); and the nine deep models "
            "excluding the ChangeFormer-style implementation (re-designed "
            "lightweight variant, Section~\\ref{sec:arch}); the final block "
            "pools the three regions.}",
            "\\label{tab:perclass-range}",
            "\\begin{adjustwidth}{-\\extralength}{0cm}",
            "\\small",
            "\\begin{tabular}{l ccc}",
            "\\toprule",
            "Class & All 12 models & Deep (10) & Deep, excl. ChangeFormer (9) \\\\",
            "\\midrule"]
    for i, cls in enumerate(CLASSES):
        out.append("{} & {} & {} & {} \\\\".format(
            f"{REGION_TITLE['within']} / {CLASS_TITLE[i]}",
            rng(r_all[0][i]), rng(r_deep[0][i]), rng(r_nocf[0][i])))
        out.append(f"  {REGION_TITLE['beilunhe']} / {CLASS_TITLE[i]} & "
                   f"{rng(r_all[1][i])} & {rng(r_deep[1][i])} & {rng(r_nocf[1][i])} \\\\")
        out.append(f"  {REGION_TITLE['zhanjiang']} / {CLASS_TITLE[i]} & "
                   f"{rng(r_all[2][i])} & {rng(r_deep[2][i])} & {rng(r_nocf[2][i])} \\\\")
        out.append("\\addlinespace")
    for i, cls in enumerate(CLASSES):
        out.append(f"\\textbf{{Pooled / {CLASS_TITLE[i]}}} & "
                   f"{rng(r_all[3][i])} & {rng(r_deep[3][i])} & {rng(r_nocf[3][i])} \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{adjustwidth}",
            "\\end{table}", ""]

    # ---- leave-one-cluster-out ---------------------------------------------
    n_cl = {r: loco["regions"][r]["n_clusters_cell"] for r in ("vietnam", "beilunhe", "zhanjiang")}
    out += ["\\begin{table}[H]",
            "\\caption{Leave-one-cluster-out sensitivity. "
            "Change-$F1$ (pooled over the five seeds by summing the confusion "
            "matrices of the remaining patches) when each spatial cluster of the "
            "test-patch grid is left out. Clusters are 1024\\,px (10.24\\,km) "
            "cells, the same unit as the cluster bootstrap "
            "(Section~\\ref{sec:main}); pooled values differ slightly from the "
            "per-seed means of Table~\\ref{tab:main}. Cluster sizes (patches, "
            "share of true change pixels): "
            "within 4 clusters (3, 1, 4, 2; true change share 0.34, 0.05, 0.38, 0.23); "
            "Beilunhe 5 clusters (7, 5, 3, 2, 1; 0.73, 0.11, 0.08, 0.04, 0.05); "
            "Zhanjiang 2 clusters (9, 6; 0.69, 0.31). $\\Delta_{\\max}$ is the "
            "largest absolute change over all single-cluster removals. For "
            "Beilunhe the non-degenerate strict (connected-component) "
            "variant has 3 clusters; removing its 12-patch cluster moves "
            "U-Net+CBAM+MSA's pooled change-$F1$ from 0.369 to "
            "0.158, qualitatively like cell 1.}",
            "\\label{tab:loco}",
            "\\begin{adjustwidth}{-\\extralength}{0cm}",
            "\\small",
            "\\setlength{\\tabcolsep}{4pt}",
            "\\begin{tabular}{l" + "c" * (1 + max(n_cl.values()) + 1) + "}",
            "\\toprule",
            "Model & Full & " + " & ".join(f"w/o C{c}" for c in range(1, max(n_cl.values()) + 1))
            + " & $\\Delta_{\\max}$ \\\\",
            "\\midrule"]
    for r, title in (("vietnam", "Within (Vietnam)"), ("beilunhe", "Beilunhe"),
                     ("zhanjiang", "Zhanjiang")):
        out.append(f"\\multicolumn{{{2 + max(n_cl.values()) + 1}}}{{l}}{{{title} "
                   f"({n_cl[r]} cell clusters)}} \\\\")
        out.append("\\midrule")
        ro = loco["regions"][r]
        k = ro["n_clusters_cell"]
        for model in LOCO_MODELS:
            if model not in ro["cell"]:
                continue
            drops = ro["cell"][model]["drops"]
            cells = []
            deltas = []
            for ci in range(k):
                d = drops[f"cell{ci + 1}"]
                if "degenerate" in d:
                    cells.append("--")
                else:
                    cells.append(f"{d['F1ch']:.3f}")
                    deltas.append(abs(d["delta_F1ch"]))
            row = [LABEL[model], f"{ro['cell'][model]['baseline']['F1ch']:.3f}"]
            row += cells + [""] * (max(n_cl.values()) - k)
            row.append(f"{max(deltas):.3f}" if deltas else "--")
            out.append(" & ".join(row) + " \\\\")
        out.append("\\addlinespace")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{adjustwidth}",
            "\\end{table}", ""]

    # ------------------------------------------------------------------
    # tab:distcov — distance-response covariate control (exploratory)
    # ------------------------------------------------------------------
    dc = json.loads((RESULTS_ROOT / "distance_covariates.json").read_text())
    out += [
        r"\begin{table}[H]",
        r"\caption{Distance-response covariate control (exploratory; the 26 never-trained, non-validation Vietnam patches, five main models, five-seed per-patch binary change $F1$). $r_{\mathrm{plain}}$: per-model Pearson correlation between a patch's edge distance to the training zone and its change $F1$; $r_{\mathrm{adj}}$: the same correlation after residualising both variables on the patch's true change fraction (the main difficulty confound; change fraction is itself negatively correlated with distance, $r = -0.36$, so nearer patches genuinely contain more change). Mangrove fraction ($r = 0.71$ with change fraction) and boundary density (degenerate, 1.0 for every patch) are kept descriptively only. Pooled OLS $F1_{ch} \sim 1 + \mathrm{distance} + \mathrm{change\_frac}$: distance coefficient $-0.0053$ (SE $0.0019$, $t = -2.8$), $R^2 = 0.29$.}",
        r"\label{tab:distcov}",
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r"Model & $r_{\mathrm{plain}}$ & $r_{\mathrm{adj}}$ \\",
        r"\midrule",
    ]
    for m in ["unet", "unet_cbam", "unet_cbam_msa", "deeplabv3plus", "temporal_unet"]:
        d = dc["per_model"][m]
        out.append(f"{LABEL[m]} & {d['r_distance_plain']:.3f} & {d['r_distance_adj']:.3f} \\\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    block = "\n".join([BEGIN] + out + [END])
    p = PAPER_ROOT / "main.tex"
    text = p.read_text()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        raise SystemExit(f"marker block not found in {p}")
    p.write_text(pat.sub(lambda _m: block, text, count=1))
    print(f"updated the supporting-tables block in {p} ({len(out)} lines)")

    # ---- console summary for the text edits ---------------------------------
    print("\n=== predicted change fraction (deep, no CF), 5-seed mean ===")
    for region in REGIONS:
        vals = []
        for m in DEEP_NOCF:
            st = cm_stats(runs, m, region)
            vals.extend([x[0] for x in st if x is not None])
        print(f"  {region:10s} pred {100*min(vals):.2f}--{100*max(vals):.2f}%  "
              f"ref {100*ref_change[region]:.2f}%")
    print("\n=== per-class F1 ranges (per-seed values) ===")
    for tag, r in (("all12", r_all), ("deep10", r_deep), ("deep_noCF", r_nocf)):
        print(f"  {tag}: " + " | ".join(f"{CLASS_TITLE[i]} {r[3][i][0]:.3f}-{r[3][i][1]:.3f} (pooled)"
                                          for i in range(4)))
    print("\n=== omission / commission ranges (deep, no CF) ===")
    for label, regions in [(rg, [rg]) for rg in REGIONS] + [("pooled", REGIONS)]:
        om, co = [], []
        for m in DEEP_NOCF:
            for rg in regions:
                st = cm_stats(runs, m, rg)
                om.extend([x[1] for x in st if x is not None])
                co.extend([x[2] for x in st if x is not None])
        print(f"  {label:10s} omission {min(om):.2f}-{max(om):.2f}  "
              f"commission {min(co):.2f}-{max(co):.2f}")


if __name__ == "__main__":
    main()

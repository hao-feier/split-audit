"""Full inventory of every experiment run for this study.

Requested in review: a complete list of all executed experiments, not only the
ones that made it into the paper. This walks the results tree, counts runs per
experiment family, records which ones were superseded or invalidated, and emits
both a JSON and a LaTeX table.

Superseded / invalid entries are listed explicitly rather than deleted, because
the branch history (E3 generation 1 -> E3-B; composition-penalty v0 -> v1) is
part of the evidence and hiding it would make the pre-specified claims
unfalsifiable.

Writes results/experiment_inventory.json and prints the LaTeX block.
"""
import glob
import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(RES, "experiment_inventory.json")

# family label -> (glob, human description, status)
FAMILIES = [
    ("primary separated (I/I)", "uniform/metrics_[a-z]*_s*.json",
     "buffer-separated within-region protocol, 5 run seeds", "reported"),
    ("secondary sqrt", "random_split_k*/metrics_*.json",
     "square-root weighting replication of the interleaved sweep", "reported"),
    ("E1 interleaved sweep", "uniform/random_split_k*/metrics_*.json",
     "10 architectures x 10 split draws x 3 run seeds (k1-k3 = three-draw headline subset)", "reported"),
    ("E3-B block-interleaved", "uniform/block_*/metrics_*.json",
     "overlap-free control, 16 split seeds x 3 architectures x 2 run seeds x 2 arms",
     "reported"),
    ("E2 I/R cell", "uniform/ir_k*/metrics_*.json",
     "isolated training, random test", "reported"),
    ("E5 buffer widths", "buf*/metrics_*.json",
     "val-test buffer 1 / 2 / 4 km", "reported"),
    ("E6 leave-one-cluster-out", "leave_one_cluster_out.json",
     "cluster-level fragility of regional point estimates, 3 regions, 10 models",
     "reported"),
    ("PCC baseline", "metrics_pcc*_s*.json",
     "post-classification comparison, both weighting schemes", "reported"),
]

SUPERSEDED = [
    ("E3 generation 1", "80 runs, 4 split seeds, 5 architectures",
     "superseded by E3-B: two of its four split seeds resolved to the same "
     "test set, leaving three distinct test sets",
     "results/e3b_contrast.json (historical entries)"),
    ("composition penalty v0", "80-row penalty table",
     "INVALID: used the block training pool as the composition control; "
     "archived, not deleted",
     "results/e3b_composition_penalty_v0_INVALID.json"),
]


def count_runs(pattern):
    return len(glob.glob(os.path.join(RES, pattern)))


def main():
    rows = []
    for label, pattern, desc, status in FAMILIES:
        n = count_runs(pattern)
        rows.append({"family": label, "glob": pattern, "n_result_files": n,
                     "description": desc, "status": status})
    total = sum(r["n_result_files"] for r in rows)

    out = {
        "families": rows,
        "total_result_files": total,
        "superseded_or_invalid": [
            {"name": a, "scale": b, "reason": c, "artefact": d}
            for a, b, c, d in SUPERSEDED],
        "note": ("Counts are result files, not training runs: a single metrics "
                 "file summarises one trained model. Checkpoints under "
                 "*/checkpoints/ are the run-level record."),
        "checkpoint_files": len(glob.glob(os.path.join(RES, "**", "checkpoints", "*.pt"),
                                          recursive=True)),
        "analysis_scripts": sorted(
            os.path.relpath(p, ROOT)
            for p in glob.glob(os.path.join(ROOT, "analysis", "*.py"))),
    }
    json.dump(out, open(OUT, "w"), indent=2)

    print(f"{'family':28s} {'files':>6s}  status")
    for r in rows:
        print(f"{r['family']:28s} {r['n_result_files']:6d}  {r['status']}")
    print(f"{'TOTAL':28s} {total:6d}")
    print(f"checkpoints: {out['checkpoint_files']}")
    print(f"analysis scripts: {len(out['analysis_scripts'])}")
    print(f"\nwrote {OUT}")

    print("\n%% ===== AUTO-GENERATED by analysis/experiment_inventory.py =====")
    print("\\begin{tabular}{lrl}")
    print("\\toprule")
    print("Experiment family & Result files & Status \\\\")
    print("\\midrule")
    for r in rows:
        print(f"{r['family']} & {r['n_result_files']} & {r['status']} \\\\")
    print("\\midrule")
    print(f"\\multicolumn{{2}}{{l}}{{\\emph{{superseded or invalid, retained as evidence}}}} \\\\")
    for a, b, c, d in SUPERSEDED:
        print(f"{a} & --- & superseded/invalid: {c[:58]}... \\\\")
    print("\\bottomrule")
    print("\\end{tabular}")
    print("%% ===== END AUTO-GENERATED =====")


if __name__ == "__main__":
    main()
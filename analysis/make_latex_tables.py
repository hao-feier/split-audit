r"""Emit LaTeX tables (booktabs) from results/metrics_summary.json into the
AUTO-GENERATED marker block in paper/main.tex, so the paper's numbers always
come from the same aggregation as results/table_main.md (single source of
truth) and the manuscript stays self-contained (no \input files).

Regenerate after every aggregation run:
    python3 analysis/aggregate_results.py [--include-pilot]
    python3 analysis/make_latex_tables.py
"""
import json
import re

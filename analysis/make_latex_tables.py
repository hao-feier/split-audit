import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from mangrove.paths import RESULTS_ROOT, PAPER_ROOT

ROOT = Path(__file__).resolve().parent.parent
# The primary model comparison is reported under the uniform (unweighted)
# class-weighting scheme selected by the strictest pre-specified,
# training-only protocol (nested spatial 3-fold CV on the training zone;
# paper Section "Sensitivity to Class Weighting"). The square-root sweep
# (RESULTS_ROOT) remains the source for the secondary-protocol tables
# (tab:cw U-Net A/B, tab:rand counterfactual baseline) and for the
# pixel-level baselines, which carry no class weights.
PRIMARY_ROOT = Path(os.environ.get("MANGROVE_PRIMARY_ROOT",
                                   str(ROOT / "results" / "uniform")))

MODELS = ["random_forest", "svm_rbf", "unet", "unet_cbam", "deeplabv3plus",
          "temporal_unet", "temporal_unet_gn", "fc_siam", "changeformer",
          "deeplabv3plus_pre", "unet_cbam_msa"]  # attention variant last; unet_msa (ablation)
          # is reported in the Discussion, not in this table
LABEL = {
    "unet": "U-Net (Exp0)",
    "unet_cbam": "U-Net+CBAM (Exp1)",
    "unet_msa": "U-Net+MSA (ablation)",
    "unet_cbam_msa": "U-Net+CBAM+MSA (Exp2)",
    "deeplabv3plus": "DeepLabv3+",
    "temporal_unet": "Temporal U-Net",
    "temporal_unet_gn": "Temporal U-Net (GroupNorm)",
    "fc_siam": "FC-Siam (SOTA baseline)",
    "changeformer": "ChangeFormer-style (Transformer)",
    "deeplabv3plus_pre": "DeepLabv3+ (ImageNet-pretrained)",
    "random_forest": "Random Forest (pixel)",
    "svm_rbf": "SVM (RBF, pixel)",
}
REGIONS = ["within", "beilunhe", "zhanjiang"]
REGION_TITLE = {"within": "within (Vietnam)", "beilunhe": "Beilunhe", "zhanjiang": "Zhanjiang"}


def binary_from_cm(cm):
    """(F1_change, commission) from a 4-class confusion matrix; changed = {1,2}."""
    cm = np.asarray(cm, dtype=np.float64)
    ch, un = [1, 2], [0, 3]
    tp = cm[np.ix_(ch, ch)].sum()
    fp = cm[np.ix_(un, ch)].sum()
    fn = cm[np.ix_(ch, un)].sum()
    prec = tp / max(tp + fp, 1)
    rec = tp / max(tp + fn, 1)
    return (2 * prec * rec / max(prec + rec, 1e-12), fp / max(tp + fp, 1))


def ms(vals, nd=3):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    mu = float(np.mean(vals))
    if len(vals) == 1:
        return f"{mu:.{nd}f}"
    sd = float(np.std(vals, ddof=1))
    return f"{mu:.{nd}f}\\,\\scriptsize$\\pm${sd:.{nd}f}"


def cell(rec, key):
    if not rec:
        return "--"
    return rec.get(key)


def main():
    # sqrt sweep: secondary protocol + pixel baselines
    # MANGROVE_PRIMARY_METRICS switches the primary tables onto the
    # de-duplicated mosaic evaluation (analysis/make_mosaic_summary.py). The
    # pooled file is the default; both are kept so the correction is a
    # one-variable, reversible choice rather than an in-place edit.
    _pm = os.environ.get("MANGROVE_PRIMARY_METRICS", "metrics_summary.json")
    sqrt_runs = json.loads((RESULTS_ROOT / "metrics_summary.json").read_text())
    # uniform sweep: primary comparison; falls back to the sqrt summary
    # when the top-up has not been aggregated yet
    pf = PRIMARY_ROOT / _pm
    print("primary metrics file: %s" % _pm)
    if PRIMARY_ROOT.resolve() != RESULTS_ROOT.resolve() and pf.exists():
        runs = {**sqrt_runs, **json.loads(pf.read_text())}
    else:
        runs = sqrt_runs

    def fmt(model, region, metric):
        s = runs.get(model, {})
        return ms([s[seed].get(region, {}).get(metric) for seed in s])

    def fmt_sqrt(model, region, metric):
        s = sqrt_runs.get(model, {})
        return ms([s[seed].get(region, {}).get(metric) for seed in s])

    out = ["% AUTO-GENERATED by analysis/make_latex_tables.py — do not edit.",
           "% Source of truth: results/metrics_summary.json", ""]

    # ---- main comparison table -------------------------------------------
    out += ["\\begin{table}[H]",
            "\\caption{Change-detection performance under the uniform (unweighted) "
            "class-weighting scheme --- the scheme selected by the strictest pre-specified, "
            "training-only protocol (nested spatial 3-fold CV on the training zone) "
            "--- as mean $\\pm$ std over the five seeds 2026--2030 "
            "(pixel-level baselines: single run). "
            "`Within' is the buffer-isolated held-out zone of the training region (Vietnam); "
            "Beilunhe and Zhanjiang are geographically disjoint test regions. "
            "$F1_{ch}$ / $IoU_{ch}$: binary change detection (loss + gain vs. unchanged) "
            + ("\\ \\emph{Metrics are computed on a de-duplicated mosaic:} the "
               "test patches are 512-px windows on a 256-px stride, so a pooled "
               "per-patch confusion matrix counts a pixel once per covering patch "
               "(1.85--2.50$\\times$, up to 4$\\times$). Every pixel in the union "
               "of the test footprints is therefore assigned to exactly one test "
               "patch (nearest covering patch) before the confusion matrix is "
               "formed. The three assignment rules agree to $\\leq$0.02 $F1_{ch}$ "
               "and the per-region leader is unchanged, so the rule is a free "
               "choice; the pooled numbers are inflated by the duplication. Pixel "
               "baselines have no patch-level output and are pooled, as marked.}"
               if _pm != "metrics_summary.json" else
               "collapsed from the four-class output.}"),  # noqa: E501
            "\\label{tab:main}",
            "\\centering",
            "\\footnotesize",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\resizebox{\\textwidth}{!}{%",
            "\\begin{tabular}{llcccccc}",
            "\\toprule",
            " & & \\multicolumn{3}{c}{Overall} & \\multicolumn{2}{c}{Change class} \\\\",
            "\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}",
            "Model & Region & OA & Kappa & mIoU & $F1_{ch}$ & $IoU_{ch}$ \\\\",
            "\\midrule"]
    for model in MODELS:
        if model not in runs:
            continue
        first = True
        for region in REGIONS:
            if region not in {r for s in runs[model].values() for r in s}:
                continue
            name = LABEL[model] if first else ""
            first = False
            out.append("{} & {} & {} & {} & {} & {} & {} \\\\".format(
                name, REGION_TITLE[region],
                fmt(model, region, "OA"), fmt(model, region, "kappa"),
                fmt(model, region, "mIoU"), fmt(model, region, "F1_change"),
                fmt(model, region, "IoU_change")))
        out.append("\\addlinespace")
    out += ["\\bottomrule", "\\end{tabular}}",
            "\\end{table}", ""]

    # ---- per-class F1 table ----------------------------------------------
    out += ["\\begin{table}[H]",
            "\\caption{Per-class F1 (mean over seeds). Classes: stable mangrove, "
            "loss (mangrove removed), gain (mangrove added), and stable background.}",
            "\\label{tab:perclass}",
            "\\begin{adjustwidth}{-\\extralength}{0cm}",
            "\\small",
            "\\begin{tabularx}{\\fulllength}{l>{\\raggedright\\arraybackslash}Xcccc}",
            "\\toprule",
            "Model & Region & Stable mangrove & Loss & Gain & Stable background \\\\",
            "\\midrule"]
    for model in MODELS:
        if model not in runs:
            continue
        for region in REGIONS:
            cells = []
            any_val = False
            for cls in ["stable_mangrove", "loss", "gain", "stable_background"]:
                vals = [runs[model][s].get(region, {}).get("per_class", {}).get(cls, {}).get("F1")
                        for s in runs[model]]
                vals = [v for v in vals if v is not None]
                if vals:
                    any_val = True
                cells.append(ms(vals))
            if any_val:
                out.append(f"{LABEL[model]} & {REGION_TITLE[region]} & " + " & ".join(cells) + " \\\\")
        out.append("\\addlinespace")
    out += ["\\bottomrule", "\\end{tabular}}",
            "\\end{table}", ""]

    # ---- class-weight sensitivity: matched 3-seed A/B on U-Net -------------
    # Preferred: robust 3-seed A/B matched to the main-sweep recipe (100 ep,
    # patience 15, batch 8, v2 split). The sqrt row reuses the main-sweep U-Net
    # (results/); inv + uniform(none) are matched re-runs in results/probes_cw/.
    # Falls back to the legacy single-seed 25-epoch probes if those are absent.
    # Per-source seed sets: inv is a three-seed matched re-run; sqrt and
    # uniform reuse the five-seed secondary and primary sweeps.
    CW_SRC = [("inv", RESULTS_ROOT / "probes_cw" / "inv", ["2026", "2027", "2028"]),
              ("sqrt", RESULTS_ROOT, ["2026", "2027", "2028", "2029", "2030"]),
              ("uniform", PRIMARY_ROOT, ["2026", "2027", "2028", "2029", "2030"])]

    def cw_block(rec, label):
        if not rec:
            return None
        if label == "within":
            return rec.get("test_within_region")
        return (rec.get("independent_test") or {}).get(label)

    def cw_load(cwd, seed):
        p = cwd / ("metrics_unet_s%s.json" % seed)
        return json.loads(p.read_text()) if p.exists() else None

    if all(cw_load(cwd, s) is not None for _, cwd, seeds in CW_SRC for s in seeds):
        out += ["\\begin{table}[H]",
                "\\caption{Class-weight sensitivity: the same U-Net trained with "
                "inverse-frequency (inv), sqrt, or uniform (none) class weights "
                "under an identical recipe matched to the main sweep (100 epochs, "
                "early-stop patience 15, batch 8, v2 split); the uniform and sqrt "
                "rows are the U-Net of the primary (uniform) and secondary "
                "(square-root) five-seed sweeps and the inv row is a three-seed "
                "matched re-run. Change classes are 0.8--2.7\\% of the evaluated "
                "pixels. Values are mean $\\pm$ std over seeds (five for sqrt and "
                "uniform, three for inv); Commission $= 1 - $ precision of the "
                "binary change class.}",
                "\\label{tab:cw}",
                "\\begin{tabular}{llrrrr}",
                "\\toprule",
                "Weight & Eval set & OA & mIoU & $F1_{ch}$ & Commission \\\\",
                "\\midrule"]
        for tag, cwd, seeds in CW_SRC:
            first = True
            for label in REGIONS:
                oas, mius, f1s, coms = [], [], [], []
                for s in seeds:
                    blk = cw_block(cw_load(cwd, s), label)
                    if not blk or "confusion_matrix" not in blk:
                        continue
                    f1c, com = binary_from_cm(blk["confusion_matrix"])
                    oas.append(blk["OA"]); mius.append(blk["mIoU"])
                    f1s.append(f1c); coms.append(com)
                name = tag if first else ""
                first = False
                out.append("{} & {} & {} & {} & {} & {} \\\\".format(
                    name, label, ms(oas), ms(mius), ms(f1s), ms(coms)))
            out.append("\\addlinespace")
        out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    else:
        probes = sorted((RESULTS_ROOT / "probes").glob("metrics_unet_cwprobe_*.json"))
        if probes:
            out += ["\\begin{table}[H]",
                    "\\caption{Class-weight sensitivity (single U-Net, identical "
                    "25-epoch schedule, batch 8, same GPU; single seed). Change "
                    "classes are 0.8--2.7\\% of pixels.}",
                    "\\label{tab:cw}",
                    "\\begin{tabular}{llrrrr}",
                    "\\toprule",
                    "Weight & Eval set & OA & mIoU & $F1_{ch}$ & Commission \\\\",
                    "\\midrule"]
            for f in probes:
                tag = f.stem.split("cwprobe_")[-1]
                rec = json.loads(f.read_text())
                for label, block in (("within", rec.get("test_within_region")),
                                      ("beilunhe", (rec.get("independent_test") or {}).get("beilunhe")),
                                      ("zhanjiang", (rec.get("independent_test") or {}).get("zhanjiang"))):
                    if not block:
                        continue
                    f1ch, com = binary_from_cm(block["confusion_matrix"])
                    out.append("{} & {} & {:.3f} & {:.3f} & {:.3f} & {:.3f} \\\\".format(
                        tag, label, block["OA"], block["mIoU"], f1ch, com))
            out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    # ---- spatial-autocorrelation control (random-split counterfactual) -----
    # tab:rand reports the honest/leaky contrast for the FULL architecture set
    # (10 deep models, incl. the unet_msa ablation that tab:main omits), so it
    # carries its own model list rather than reusing the global MODELS.
    TAB_RAND_MODELS = ["unet", "unet_cbam", "unet_msa", "unet_cbam_msa",
                       "deeplabv3plus", "deeplabv3plus_pre", "temporal_unet",
                       "temporal_unet_gn", "fc_siam", "changeformer"]
    cmp_file = PRIMARY_ROOT / "random_split" / "comparison.json"
    if not cmp_file.exists():
        cmp_file = RESULTS_ROOT / "random_split" / "comparison.json"
    if cmp_file.exists():
        comp = json.loads(cmp_file.read_text())
        order = [m for m in TAB_RAND_MODELS if m in comp]
        if order:
            _sum = json.loads((PRIMARY_ROOT / "metrics_summary.json").read_text())

            def _raw_gap(model):
                """Gap from UNROUNDED means of the SAME counterfactual sweep.

                Both arms come from results/uniform/random_split/comparison.json:
                `honest` = the buffer-isolated arm (rnd_iso), `leaky` = the
                interleaved arm (rnd_rnd). Using one sweep for both is what
                makes the contrast like-for-like: identical training zone,
                validation zone, recipe and run seeds, differing only in the
                spatial assignment of the test patches.

                The honest arm used to be the PRIMARY five-seed sweep
                (metrics_summary.json `within`). That mixed conventions: the
                primary sweep keeps all five seeds, so a collapsed
                all-background run entered the honest mean, while the leaky arm
                had collapsed runs removed when comparison.json was built.
                For ChangeFormer that pulled the honest mean from 0.058 to 0.019
                and inflated its gap by ~4 pp. Do not reintroduce it.

                Subtracting the printed cells instead gives +31.6 for fc_siam
                where the underlying data gives +31.7, because the displayed F1
                is rounded to 3 dp first, so compute from the unrounded values.
                """
                import statistics as _st
                h = _st.mean([r["F1_change"] for r in comp[model]["rnd_iso"].values()])
                l = _st.mean([r["F1_change"] for r in comp[model]["rnd_rnd"].values()])
                return 100 * (l - h)

            def rcell(model, proto, metric):
                if proto == "rnd_iso":
                    # honest protocol == the buffer-isolated arm of the SAME
                    # counterfactual sweep (rnd_iso), so both cells of the
                    # contrast share training zone, recipe and run seeds.
                    rows = comp[model][proto]
                    vals = [rows[s].get(metric) for s in rows
                            if rows[s].get(metric) is not None]
                    return ms(vals)
                rows = comp[model][proto]
                vals = [rows[s].get(metric) for s in rows if rows[s].get(metric) is not None]
                return ms(vals)
            def short(model):
                return LABEL[model].split(" (")[0]   # drop "(ExpN, proposed)" -> narrower
            # collapse bookkeeping -> data-driven caption + footnote
            excl = comp.get("_config", {}).get("excluded_collapsed_runs", [])
            n_runs = {m: len(comp[m]["rnd_rnd"]) for m in order}
            full_runs = max(n_runs.values()) if n_runs else 0
            n_iso = {m: len(comp[m]["rnd_iso"]) for m in order}
            run_desc = ("3 split draws $\\times$ 3 run seeds (eight to nine runs "
                        "per model, four for ChangeFormer-style")
            odd = sorted({n for n in set(list(n_runs.values()) + list(n_iso.values()))
                          if n != full_runs})
            if odd:
                run_desc += ("; %s once collapsed runs are removed"
                             % ", ".join(str(n) for n in odd))
            run_desc += ")"
            if excl:
                fam = sorted({e.split("/")[0] for e in excl})
                _nice = {"changeformer": "ChangeFormer-style",
                         "temporal_unet_gn": "Temporal U-Net (GN)",
                         "unet": "U-Net", "unet_cbam": "U-Net+CBAM",
                         "unet_cbam_msa": "U-Net+CBAM+MSA",
                         "deeplabv3plus": "DeepLabv3+",
                         "deeplabv3plus_pre": "DeepLabv3+ (pretrained)",
                         "unet_msa": "U-Net+MSA", "temporal_unet": "Temporal U-Net",
                         "fc_siam": "FC-Siam"}
                fam_tex = ", ".join(_nice.get(f, f.replace("_", "\\_"))
                                    for f in fam)
                note = ("\\footnotesize Both arms of the contrast exclude runs "
                        "that collapsed to an all- or near-all-background solution "
                        "($F1_{ch}<0.05$; %d runs, %s), "
                        "removed symmetrically when the sweep results were written; "
                        "the affected families are unstable under the class "
                        "imbalance rather than mis-measured, and retaining them in "
                        "one arm only would bias the gap (Section~\\ref{sec:rand})."
                        % (len(excl), fam_tex if fam_tex else "various families"))
            else:
                note = ("\\footnotesize No run collapsed to an all-background "
                        "solution in either arm.")
            out += ["\\begin{table}[H]",
                    "\\caption{Spatial-autocorrelation control (Vietnam), primary "
                    "uniform protocol. The same 60 non-buffer patches are re-assigned "
                    "to a spatially interleaved random split (40/10/10) and re-trained "
                    "and re-evaluated under an identical recipe. Both `honest' "
                    "(buffer-isolated) and `leaky' (interleaved) arms are read from "
                    "this same sweep, so the two cells share training zone, "
                    "validation zone, recipe and run seeds and differ only in the "
                    "spatial assignment of the test patches; pooled over "
                    + run_desc + ". "
                    "$F1_{ch}$ / $IoU_{ch}$: binary change (loss + gain vs. unchanged). "
                    "Mean $\\pm$ std over runs.}",
                    "\\label{tab:rand}",
                    "{\\footnotesize",
                    "\\setlength{\\tabcolsep}{3pt}",
                    "\\begin{tabular}{llrrrrrc}",
                    "\\toprule",
                    "Model & Protocol & OA & mIoU & $F1_{ch}$ & $IoU_{ch}$ & Comm. "
                    "& Gap (pp) \\\\",
                    "\\midrule"]
            for model in order:
                for pi, proto in enumerate(("rnd_iso", "rnd_rnd")):
                    name = short(model) if pi == 0 else ""
                    tag = "honest" if proto == "rnd_iso" else "leaky"
                    # the contrast is this paper's headline quantity, so it gets
                    # its own column rather than being left for the reader to
                    # subtract two cells
                    gap = f"${{({_raw_gap(model):+.1f})}}$" if proto == "rnd_rnd" else ""
                    out.append("{} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
                        name, tag,
                        rcell(model, proto, "OA"), rcell(model, proto, "mIoU"),
                        rcell(model, proto, "F1_change"), rcell(model, proto, "IoU_change"),
                        rcell(model, proto, "Commission"), gap))
                out.append("\\addlinespace")
            out += ["\\bottomrule", "\\end{tabular}", "}",
                    "{" + note + "}",
                    "\\end{table}", ""]

    # tab:perclass and tab:cw were removed in the restructure (off the
    # story line).  The builders above still produce them, so drop those two
    # blocks from the emitted file instead of letting a regeneration resurrect
    # deleted tables.  Block-wise and line-wise: a regex over the whole file
    # would eat the neighbours.
    _GONE = ("\\label{tab:perclass}", "\\label{tab:cw}")
    _kept, _buf, _drop = [], [], False
    for _line in out:
        if _buf:                                   # inside a table block
            _buf.append(_line)
            if any(g in _line for g in _GONE):
                _drop = True
            if _line.startswith("\\end{table}"):
                if not _drop:
                    _kept.extend(_buf)
                _buf = []
        elif _line.startswith("\\begin{table}"):   # block opens here
            _buf, _drop = [_line], False
        else:
            _kept.append(_line)
    out = _kept

    if len(out) >= 2 and out[0].startswith("% AUTO-GENERATED by") and out[1].startswith("% Source of truth"):
        out = out[2:]
    while out and out[-1] == "":
        out.pop()
    _S = "% ===== AUTO-GENERATED: paper tables — regenerate via `python3 analysis/make_latex_tables.py` (do not edit by hand) ====="
    _E = "% ===== END AUTO-GENERATED: paper tables ====="
    _main = PAPER_ROOT / "main.tex"
    _lines = _main.read_text().splitlines()
    _i, _j = _lines.index(_S), _lines.index(_E)
    _lines[_i + 1:_j] = out
    _main.write_text("\n".join(_lines) + "\n")
    print(f"wrote paper tables into main.tex between markers ({len(out)} lines)")


if __name__ == "__main__":
    main()

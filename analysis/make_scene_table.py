"""Emit the per-scene acquisition table (tab:scenes) into the marked block
of paper/main.tex, from results/scene_dates_tides.json:

  tab:scenes  the 40 composite scenes: tile, satellite, acquisition date,
              tidal state (lunar-age based) and mangrove clear fraction.

Run:
    python3 analysis/make_scene_table.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from mangrove.paths import PAPER_ROOT, RESULTS_ROOT

BEGIN = "% ===== AUTO-GENERATED by analysis/make_scene_table.py — do not edit ====="
END = "% ===== END AUTO-GENERATED by analysis/make_scene_table.py ====="

REGION_TITLE = {"vietnam": "Within (Vietnam)", "beilunhe": "Beilunhe",
                "zhanjiang": "Zhanjiang"}
REGION_ORDER = ["vietnam", "beilunhe", "zhanjiang"]
SCENE_RE = re.compile(r"S2([AB])_(\w+)_(\d{8})_")


def fmt_cf(cf):
    s = f"{cf:.4f}".rstrip("0").rstrip(".")
    return s if s else "0"


def main():
    d = json.loads((RESULTS_ROOT / "scene_dates_tides.json").read_text())
    out = ["% Sources: results/scene_dates_tides.json",
           "",
           "\\begin{table}[H]",
           "\\caption{Acquisition metadata of the 40 scenes used in the "
           "dry-season composites (Section~\\ref{sec:composites}); two scenes "
           "per tile-epoch. Tidal state from lunar age (spring: within 3\\,d of "
           "new or full moon; mid: within 6\\,d; otherwise neap), consistent "
           "with the M2-dominated semidiurnal regime of the Gulf of Tonkin / "
           "Beibu Gulf. CF = clear fraction over the mangrove mask (equal to "
           "the region-window clear fraction for all 40 scenes).}",
           "\\label{tab:scenes}",
           "\\begin{adjustwidth}{-\\extralength}{0cm}",
           "\\footnotesize",
           "\\begin{tabular}{l l l l l l c}",
           "\\toprule",
           "Region & Epoch & Tile & Satellite & Date & Tidal state & CF \\\\",
           "\\midrule"]
    n = 0
    for r in REGION_ORDER:
        out.append(f"\\multicolumn{{7}}{{l}}{{{REGION_TITLE[r]}}} \\\\")
        out.append("\\midrule")
        for epoch, esym in (("t1", "$t_1$"), ("t2", "$t_2$")):
            rows = []
            for scene, v in d["regions"][r][epoch].items():
                m = SCENE_RE.match(scene)
                s = m.group(3)
                rows.append((f"{s[0:4]}-{s[4:6]}-{s[6:8]}", m.group(2),
                             f"S2{m.group(1)}", v["tidal_state"],
                             v["cf_mangrove"]))
            for date, tile, sat, tide, cf in sorted(rows):
                out.append(f" & {esym} & {tile} & {sat} & {date} & {tide} "
                           f"& {fmt_cf(cf)} \\\\")
                n += 1
        out.append("\\addlinespace")
    out = [x for x in out if x != "\\addlinespace"]  # drop trailing one
    out += ["\\bottomrule", "\\end{tabular}", "\\end{adjustwidth}",
            "\\end{table}", ""]
    assert n == 40, f"expected 40 scenes, got {n}"

    block = "\n".join([BEGIN] + out + [END])
    p = PAPER_ROOT / "main.tex"
    text = p.read_text()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        raise SystemExit(f"marker block not found in {p}")
    p.write_text(pat.sub(lambda _m: block, text, count=1))
    print(f"updated tab:scenes block in {p} ({n} scenes, {len(out)} lines)")


if __name__ == "__main__":
    main()

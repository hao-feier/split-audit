"""Exp3e: NON-OVERLAPPING BLOCK-INTERLEAVED arm and its size-matched honest
control.

This is the overlap-free counterfactual: a spatially interleaved split
that shares NO pixels with the training set. It is only achievable at reduced
scale, and that is a finding rather than an inconvenience -- see
experiments/make_block_split.py for the feasibility probe (0 of 4000 reseeded
random permutations give zero overlap; a buffered random split keeps ZERO test
patches; the block arm keeps 19-25 train / 3-6 test against the protocol's
40/10/10).

Two arms, generated by make_block_split.py:
  *_blk<ss>.json  block-interleaved, zero footprint overlap, separated by a
                  one-block void band; every test patch sits INSIDE the training
                  extent, so the arrangement is genuinely interleaved
  *_hon<ss>.json  the isolated protocol's own zones, subsampled to EXACTLY the
                  same counts and matched on change prevalence; buffer-isolated

Both arms have identical counts, identical recipe and zero overlap, so
blk - hon isolates spatial arrangement (interleaved-but-separated vs zoned)
with neither pixel overlap, nor training-set size, nor case mix as a confound.
Each run additionally scores the SAME model on its partner arm, so the contrast
is within-model and needs no cross-model matching.

Outputs (isolated under results/uniform/block_*/ so the paper aggregator's
top-level metrics_*_s<seed>.json glob never picks these up):
  results/uniform/block_<tag>/checkpoints/<model>_s<seed>.pt
  results/uniform/block_<tag>/train_log_<model>_s<seed>.jsonl
  results/uniform/block_<tag>/metrics_<model>_s<seed>.json
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

# Pre-parse --threads so OMP_NUM_THREADS is set BEFORE `import torch` (see
# exp3_train.py note: late OMP set still spawns 64 oneDNN threads -> OOM).
_t = None
_a = sys.argv[1:]
if "--threads" in _a and _a.index("--threads") + 1 < len(_a):
    _t = _a[_a.index("--threads") + 1]
for a in _a:
    if a.startswith("--threads="):
        _t = a.split("=", 1)[1]
os.environ.setdefault("OMP_NUM_THREADS", _t or "2")
os.environ.setdefault("OMP_DYNAMIC", "FALSE")

import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import DataLoader

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from mangrove.config import SEED, TRAIN, CHANGE_CLASSES
from mangrove.datasets import ChangePatchDataset
from mangrove.metrics import cd_metrics
from mangrove.models import MODEL_REGISTRY
from mangrove.paths import RESULTS_ROOT, SPLITS_ROOT

TEMPORAL_MODELS = {"temporal_unet"}
STATIC_IN_CH = 9 * 3
TEMPORAL_IN_CH = 9
TRAIN_REGION = "vietnam"
TEST_REGIONS = ("beilunhe", "zhanjiang")

DEFAULT_SUB = "block_split"   # output dir under results/
DEFAULT_SPLIT_TAG = "_blk12"   # data/splits/vietnam_{split}_blk12.json
SPLIT_TAG = DEFAULT_SPLIT_TAG


def normalize(x):
    return x / 10000.0


def dice_loss(proba, y, smooth=1.0):
    p = proba.softmax(1)
    y_one = nn.functional.one_hot(y, p.shape[1]).float().permute(0, 3, 1, 2)
    inter = (p * y_one).sum((2, 3))
    denom = p.sum((2, 3)) + y_one.sum((2, 3))
    return 1.0 - (2.0 * inter + smooth).sum() / (denom + smooth).sum()


def _class_weights(idx, change, cw_mode):
    pix = change[np.asarray(idx)].ravel()
    counts = np.bincount(pix, minlength=4)
    counts = np.maximum(counts, 1)
    freq = counts / counts.sum()
    if cw_mode == "inv":
        w = 1.0 / (4 * freq)
    elif cw_mode == "sqrt":
        w = 1.0 / (4 * np.sqrt(freq))
    elif cw_mode == "none":
        w = np.ones(4)
    else:
        raise ValueError(f"unknown cw_mode {cw_mode}")
    return torch.tensor(w, dtype=torch.float32)


def rand_dataset(region, split, augment, concat, cw_mode):
    """Build a ChangePatchDataset whose index set is the random split for
    `split` (train/val/test) rather than the isolated one. Reuse the cached
    region arrays; swap idx; recompute class weights on the random train set."""
    split_file = SPLITS_ROOT / f"{region}{''}_{split}{SPLIT_TAG}.json"
    idx = json.loads(split_file.read_text())
    # construct with the (isolated) split to get data arrays + augment flag,
    # then override the index set.
    ds = ChangePatchDataset(region, split, augment=augment, concat=concat,
                            cw_mode=cw_mode)
    ds.idx = idx
    if split == "train":
        ds.class_weights = _class_weights(ds.idx, ds.change, cw_mode)
    return ds


def build_dataloaders(model_name, num_workers=2, batch_size=None, cw_mode="sqrt",
                      split_tag=DEFAULT_SPLIT_TAG):
    global SPLIT_TAG
    SPLIT_TAG = split_tag
    concat = model_name not in TEMPORAL_MODELS
    bs = batch_size or TRAIN["batch_size"]
    train_ds = rand_dataset(TRAIN_REGION, "train", augment=True, concat=concat,
                            cw_mode=cw_mode)
    val_ds = rand_dataset(TRAIN_REGION, "val", augment=False, concat=concat,
                          cw_mode=cw_mode)
    test_ds = rand_dataset(TRAIN_REGION, "test", augment=False, concat=concat,
                           cw_mode=cw_mode)
    # DeepLabv3+'s ASPP global-pooling branch emits a 1x1 feature map, so
    # BatchNorm there needs >= 2 samples per batch. The block arms have ragged
    # training sets (19-25 patches), so an 8-sized batch can end with a single
    # sample and crash. Drop the tail batch ONLY when the remainder is exactly
    # 1 -- any larger remainder is fine, and this costs at most one patch.
    # (The main sweep's 40-patch sets never hit this: 40 % 8 == 0.)
    n_train = len(train_ds.idx)
    rem = n_train % bs
    drop_last = (rem == 1)
    if drop_last:
        print(f"[block] train n={n_train} bs={bs} remainder 1 -> drop_last=True "
              f"({n_train - (n_train // bs) * bs} patch(es) unused per epoch)",
              flush=True)
    train_dl = DataLoader(train_ds, batch_size=bs, shuffle=True,
                          num_workers=num_workers, pin_memory=False,
                          drop_last=drop_last)
    val_dl = DataLoader(val_ds, batch_size=bs, shuffle=False, num_workers=num_workers)
    test_dl = DataLoader(test_ds, batch_size=bs, shuffle=False, num_workers=num_workers)
    return train_dl, val_dl, test_dl, train_ds


@torch.no_grad()
def evaluate(model, dl, temporal=False, device=torch.device("cpu")):
    model.eval()
    ys, ps = [], []
    for batch in dl:
        if temporal:
            x1, x2, y, _ = batch
            x1 = normalize(x1).to(device)
            x2 = normalize(x2).to(device)
            proba = model(x1, x2)
        else:
            x, y, _ = batch
            x = normalize(x).to(device)
            proba = model(x)
        ps.append(proba.argmax(1).cpu().numpy())
        ys.append(y.numpy())
    y = np.concatenate(ys)
    p = np.concatenate(ps)
    return cd_metrics(y, p, 4, CHANGE_CLASSES)


def isolated_loader(region, split, model_name, num_workers, batch_size,
                    split_tag=None):
    """Apples-to-apples: the SAME model scored on a named alternative split."""
    from mangrove.datasets import load_split
    concat = model_name not in TEMPORAL_MODELS
    if split_tag:
        idx = json.loads(
            (SPLITS_ROOT / f"{region}_{split}{split_tag}.json").read_text())
    else:
        idx = load_split(region, split)
    ds = ChangePatchDataset(region, split, augment=False, concat=concat)
    ds.idx = idx
    bs = batch_size or TRAIN["batch_size"]
    return DataLoader(ds, batch_size=bs, shuffle=False, num_workers=num_workers)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, choices=list(MODEL_REGISTRY))
    ap.add_argument("--epochs", type=int, default=TRAIN["epochs"])
    ap.add_argument("--batch-size", type=int, default=TRAIN["batch_size"])
    ap.add_argument("--lr", type=float, default=TRAIN["lr"])
    ap.add_argument("--patience", type=int, default=15)
    ap.add_argument("--num-workers", type=int, default=TRAIN["num_workers"])
    ap.add_argument("--cw-mode", choices=["inv", "sqrt", "none"], default="sqrt")
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--threads", type=int, default=None)
    ap.add_argument("--device", choices=["auto", "cuda", "cpu"], default="auto")
    ap.add_argument("--split-tag", default=DEFAULT_SPLIT_TAG,
                    help="suffix of data/splits/vietnam_{split}<tag>.json, e.g. _blk12")
    ap.add_argument("--partner-tag", default=None,
                    help="suffix of the size-matched partner arm, e.g. _hon12")
    ap.add_argument("--out-subdir", default=DEFAULT_SUB,
                    help="output dir under results/ (default: random_split)")
    args = ap.parse_args()
    global SUB
    SUB = RESULTS_ROOT / args.out_subdir
    SPLIT_TAG = args.split_tag
    if args.threads:
        os.environ["OMP_NUM_THREADS"] = str(args.threads)
        torch.set_num_threads(args.threads)

    if args.device == "cuda" or (args.device == "auto" and torch.cuda.is_available()):
        device = torch.device("cuda")
        torch.cuda.empty_cache()
    else:
        device = torch.device("cpu")

    model_name = args.model
    seed = args.seed
    torch.manual_seed(seed)
    np.random.seed(seed)
    import random
    random.seed(seed)

    SUB.mkdir(parents=True, exist_ok=True)
    (SUB / "checkpoints").mkdir(parents=True, exist_ok=True)
    ckpt = SUB / "checkpoints" / f"{model_name}_s{seed}.pt"
    log_path = SUB / f"train_log_{model_name}_s{seed}.jsonl"
    metrics_path = SUB / f"metrics_{model_name}_s{seed}.json"
    log_path.write_text("")   # fresh log each run

    train_dl, val_dl, test_dl, train_ds = build_dataloaders(
        model_name, num_workers=args.num_workers, batch_size=args.batch_size,
        cw_mode=args.cw_mode, split_tag=SPLIT_TAG)
    is_temporal = model_name in TEMPORAL_MODELS
    in_ch = TEMPORAL_IN_CH if is_temporal else STATIC_IN_CH
    model = MODEL_REGISTRY[model_name](in_ch=in_ch, out_ch=4).to(device)
    n_params = sum(p.numel() for p in model.parameters())
    print(f"[block] model={model_name} in_ch={in_ch} params={n_params/1e6:.2f}M "
          f"device={device} train={len(train_dl)} val={len(val_dl)} test={len(test_dl)} "
          f"cw_mode={args.cw_mode} seed={seed}", flush=True)

    opt = torch.optim.Adam(model.parameters(), lr=args.lr, weight_decay=TRAIN["weight_decay"])
    crit_ce = nn.CrossEntropyLoss(weight=train_ds.class_weights.to(device))
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs)

    best_loss, best_state, bad = float("inf"), None, 0
    t0 = time.time()
    for epoch in range(1, args.epochs + 1):
        model.train()
        run_loss, n = 0.0, 0
        for batch in train_dl:
            if is_temporal:
                x1, x2, y, _ = batch
                x1, x2 = normalize(x1).to(device), normalize(x2).to(device)
                y = y.to(device)
                out = model(x1, x2)
            else:
                x, y, _ = batch
                x = normalize(x).to(device)
                y = y.to(device)
                out = model(x)
            opt.zero_grad()
            loss = crit_ce(out, y) + dice_loss(out, y)
            loss.backward()
            opt.step()
            run_loss += float(loss.detach()) * y.size(0)
            n += y.size(0)
        sched.step()
        val = evaluate(model, val_dl, temporal=is_temporal, device=device)
        val_loss = 1.0 - val["mIoU"]
        dur = time.time() - t0
        rec = {"epoch": epoch, "train_loss": run_loss / n, "val_OA": val["OA"],
               "val_F1": val["F1_macro"], "val_mIoU": val["mIoU"],
               "elapsed_min": round(dur / 60, 1), "lr": opt.param_groups[0]["lr"]}
        print(json.dumps(rec), flush=True)
        with open(log_path, "a") as fh:
            fh.write(json.dumps(rec) + "\n")
        if val_loss < best_loss - 1e-4:
            best_loss, bad = val_loss, 0
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
        else:
            bad += 1
            if bad >= args.patience:
                print(f"[block] early stop at epoch {epoch}", flush=True)
                break

    if best_state is None:
        best_state = {k: v.cpu() for k, v in model.state_dict().items()}
    torch.save(best_state, ckpt)
    model.load_state_dict(torch.load(ckpt, map_location="cpu"))

    # random (interleaved) test = the "leaky" number
    rand_test = evaluate(model, test_dl, temporal=is_temporal, device=device)
    # the size-matched partner arm, scored with the SAME model
    partner_test = None
    if args.partner_tag:
        iso_dl = isolated_loader(TRAIN_REGION, "test", model_name,
                                 num_workers=args.num_workers,
                                 batch_size=args.batch_size,
                                 split_tag=args.partner_tag)
        partner_test = evaluate(model, iso_dl, temporal=is_temporal, device=device)
    # independent regions (schema parity)
    indep = {}
    for region in TEST_REGIONS:
        if not (SPLITS_ROOT / f"{region}_test.json").exists():
            indep[region] = None
            continue
        ds = ChangePatchDataset(region, "test", augment=False, concat=not is_temporal)
        dl = DataLoader(ds, batch_size=TRAIN["batch_size"], shuffle=False,
                        num_workers=args.num_workers)
        indep[region] = evaluate(model, dl, temporal=is_temporal, device=device)

    res = {
        "model": model_name, "params_M": round(n_params / 1e6, 3), "seed": seed,
        "in_ch": in_ch, "split": "block", "split_tag": SPLIT_TAG,
        "partner_tag": args.partner_tag,
        "hyperparams": {k: args.__dict__[k] for k in
                        ("epochs", "batch_size", "lr", "patience", "seed", "cw_mode")},
        "block_test": rand_test,
        "partner_test": partner_test,
        "independent_test": indep,
        "elapsed_h": round((time.time() - t0) / 3600, 2),
    }
    metrics_path.write_text(json.dumps(res, indent=2))

    def _f(m, k):
        return f"{m[k]:.4f}" if m else "n/a"
    print(f"[block] DONE {model_name} s{seed} tag={SPLIT_TAG}: "
          f"block_test OA={_f(rand_test,'OA')} mIoU={_f(rand_test,'mIoU')} | "
          f"partner OA={_f(partner_test,'OA')} mIoU={_f(partner_test,'mIoU')} "
          f"({res['elapsed_h']} h)", flush=True)


if __name__ == "__main__":
    main()
